interface LanguageContextValue {
    language: Language;
    setLanguage: (language: Language) => void;
    t: (english: string) => string;
}

const LanguageContext = createContext<LanguageContextValue | null>(null);
const storageKey = 'settlers-language';

export function LanguageProvider({ children }: { children: ReactNode }) {
    const [language, setLanguage] = useState<Language>(() => {
        try { return localStorage.getItem(storageKey) === 'tl' ? 'tl' : 'en'; }
        catch { return 'en'; }
    });

    useEffect(() => {
        document.documentElement.lang = language === 'tl' ? 'fil' : 'en';
        try { localStorage.setItem(storageKey, language); } catch { /* Storage may be disabled. */ }
    }, [language]);

    const value = useMemo<LanguageContextValue>(() => ({
        language,
        setLanguage,
        t: (english: string) => language === 'tl' ? tagalog[english] ?? english : english,
    }), [language]);

    return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
    const context = useContext(LanguageContext);
    if (!context) throw new Error('useLanguage must be used within LanguageProvider');
    return context;
}
